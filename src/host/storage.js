import { mkdir, readFile, rename, writeFile } from "node:fs/promises";
import { basename, isAbsolute, join, normalize, relative, resolve, sep } from "node:path";
import { randomUUID } from "node:crypto";
import { DEFAULT_FOLD_DIR_NAME } from "../shared/constants.js";
import { formatTurnRangeChinese, normalizeTurns, parseFoldMarkdown, serializeFoldMarkdown } from "../shared/markdown.js";

/**
 * Resolve the storage directory for a session inside its workspace.
 */
export function getSessionFoldDir(workspaceRoot, sessionId, foldDirName = DEFAULT_FOLD_DIR_NAME) {
  const safeSession = sanitizeSegment(sessionId || "default-session");
  const base = resolve(workspaceRoot, foldDirName);
  const dir = resolve(base, safeSession);
  assertInside(base, dir);
  return dir;
}

/**
 * Guard against path traversal outside root.
 */
export function assertInside(root, target) {
  const normRoot = normalize(resolve(root));
  const normTarget = normalize(resolve(target));
  const rel = relative(normRoot, normTarget);
  if (rel.startsWith("..") || isAbsolute(rel)) {
    throw new Error(`路径越界：${target} 不在允许目录 ${root} 内`);
  }
  return normTarget;
}

/**
 * Atomically write UTF-8 text to disk (write temp file + rename).
 */
async function atomicWriteText(filePath, content) {
  const tmpPath = `${filePath}.${randomUUID().slice(0, 8)}.tmp`;
  await writeFile(tmpPath, content, "utf8");
  await rename(tmpPath, filePath);
}

/**
 * Load session fold registry (`folds.json`), creating an empty state if absent.
 */
export async function loadSessionState(workspaceRoot, sessionId, foldDirName = DEFAULT_FOLD_DIR_NAME) {
  const dir = getSessionFoldDir(workspaceRoot, sessionId, foldDirName);
  const statePath = join(dir, "folds.json");
  try {
    const raw = await readFile(statePath, "utf8");
    const parsed = JSON.parse(raw);
    return {
      version: 1,
      sessionId,
      marks: Array.isArray(parsed.marks) ? parsed.marks : [],
      folds: Array.isArray(parsed.folds) ? parsed.folds : [],
      drafts: Array.isArray(parsed.drafts) ? parsed.drafts : [],
    };
  } catch (err) {
    if (err && err.code === "ENOENT") {
      return {
        version: 1,
        sessionId,
        marks: [],
        folds: [],
        drafts: [],
      };
    }
    throw err;
  }
}

/**
 * Ensure the root `.dsh-folds/` directory exists and contains a `.gitignore`
 * so folded archives never pollute user Git repositories.
 */
async function ensureFoldRoot(workspaceRoot, foldDirName = DEFAULT_FOLD_DIR_NAME) {
  const base = resolve(workspaceRoot, foldDirName);
  await mkdir(base, { recursive: true });
  const gitignorePath = join(base, ".gitignore");
  try {
    await readFile(gitignorePath, "utf8");
  } catch (err) {
    if (err && err.code === "ENOENT") {
      await atomicWriteText(
        gitignorePath,
        "# Auto-generated by dsh-context-fold so folded session archives stay out of Git\n*\n"
      );
    }
  }
  return base;
}

/**
 * Save session fold registry (`folds.json`) and regenerate `INDEX.md`.
 */
export async function saveSessionState(workspaceRoot, sessionId, state, foldDirName = DEFAULT_FOLD_DIR_NAME) {
  await ensureFoldRoot(workspaceRoot, foldDirName);
  const dir = getSessionFoldDir(workspaceRoot, sessionId, foldDirName);
  await mkdir(dir, { recursive: true });
  const statePath = join(dir, "folds.json");
  await atomicWriteText(statePath, JSON.stringify(state, null, 2) + "\n");
  await writeIndexMarkdown(dir, state);
  return statePath;
}

/**
 * Create a new editable Markdown draft file on disk and register it in `state.drafts`.
 */
export async function saveDraftFile({
  workspaceRoot,
  sessionId,
  foldDirName = DEFAULT_FOLD_DIR_NAME,
  foldId,
  title,
  turns,
  startTurn,
  endTurn,
  startSeq,
  endSeq,
  segments,
  originalTokens,
  foldedTokens,
  generatedBy,
  summary,
  details,
}) {
  await ensureFoldRoot(workspaceRoot, foldDirName);
  const dir = getSessionFoldDir(workspaceRoot, sessionId, foldDirName);
  await mkdir(dir, { recursive: true });

  const state = await loadSessionState(workspaceRoot, sessionId, foldDirName);
  const nextSeqNum = state.folds.length + state.drafts.length + 1;
  const prefix = String(nextSeqNum).padStart(2, "0");
  const resolvedTurns = normalizeTurns(turns, startTurn, endTurn);
  const slug = slugifyTitle(title) || `turns-${resolvedTurns[0] ?? startTurn}-${resolvedTurns[resolvedTurns.length - 1] ?? endTurn}`;
  const fileName = `${prefix}-${slug}-${foldId.slice(0, 6)}.md`;
  const filePath = assertInside(dir, join(dir, fileName));

  const now = new Date().toISOString();
  const markdown = serializeFoldMarkdown({
    foldId,
    title,
    sessionId,
    turns: resolvedTurns,
    startTurn: resolvedTurns[0] ?? startTurn,
    endTurn: resolvedTurns[resolvedTurns.length - 1] ?? endTurn,
    startSeq,
    endSeq,
    checkpointSeq: null,
    originalTokens,
    foldedTokens,
    generatedBy,
    createdAt: now,
    updatedAt: now,
    summary,
    details,
  });

  await atomicWriteText(filePath, markdown);

  const relPath = relative(workspaceRoot, filePath).split(sep).join("/");
  const draft = {
    foldId,
    title,
    turns: resolvedTurns,
    startTurn: resolvedTurns[0] ?? startTurn,
    endTurn: resolvedTurns[resolvedTurns.length - 1] ?? endTurn,
    startSeq,
    endSeq,
    ...(Array.isArray(segments) ? { segments } : {}),
    originalTokens,
    foldedTokens,
    generatedBy,
    fileName,
    filePath,
    relativePath: relPath,
    createdAt: now,
    updatedAt: now,
  };

  state.drafts = state.drafts.filter((d) => d.foldId !== foldId);
  state.drafts.push(draft);
  await saveSessionState(workspaceRoot, sessionId, state, foldDirName);

  return { draft, markdown, filePath, relativePath: relPath };
}

/**
 * Read a fold or draft Markdown file safely from disk and parse it.
 */
export async function readFoldFile(workspaceRoot, sessionId, filePathOrName, foldDirName = DEFAULT_FOLD_DIR_NAME) {
  const dir = getSessionFoldDir(workspaceRoot, sessionId, foldDirName);
  const resolved = isAbsolute(filePathOrName)
    ? assertInside(dir, filePathOrName)
    : assertInside(dir, join(dir, basename(filePathOrName)));
  const raw = await readFile(resolved, "utf8");
  return {
    filePath: resolved,
    raw,
    parsed: parseFoldMarkdown(raw),
  };
}

/**
 * Update a fold or draft Markdown file on disk cleanly.
 */
export async function updateFoldFile({
  workspaceRoot,
  sessionId,
  filePath,
  foldDirName = DEFAULT_FOLD_DIR_NAME,
  title,
  summary,
  details,
  patchMeta = {},
}) {
  const dir = getSessionFoldDir(workspaceRoot, sessionId, foldDirName);
  const safePath = assertInside(dir, filePath);
  const raw = await readFile(safePath, "utf8");
  const parsed = parseFoldMarkdown(raw);
  const now = new Date().toISOString();

  const updatedMarkdown = serializeFoldMarkdown({
    ...parsed.meta,
    ...patchMeta,
    foldId: patchMeta.foldId ?? parsed.meta.foldId ?? randomUUID(),
    sessionId,
    title: title ?? parsed.title,
    summary: summary ?? parsed.summary,
    details: details ?? parsed.details,
    updatedAt: now,
  });

  await atomicWriteText(safePath, updatedMarkdown);
  return { filePath: safePath, markdown: updatedMarkdown, updatedAt: now };
}

/**
 * Write a human-readable INDEX.md summarizing all committed folds in this session.
 */
async function writeIndexMarkdown(dir, state) {
  const lines = [
    `# 上下文折出档案索引`,
    "",
    `- 会话 ID：\`${state.sessionId}\``,
    `- 已折出段落数：${state.folds.length}`,
    `- 更新时间：${new Date().toISOString()}`,
    "",
  ];

  if (state.folds.length === 0) {
    lines.push("_尚无已折出的段落。_");
  } else {
    lines.push("| # | 标题 | 轮次 | 原 Token | 折后 Token | 节省 | 文件 |");
    lines.push("|---|---|---|---:|---:|---:|---|");
    state.folds.forEach((f, idx) => {
      const saved = Math.max(0, (f.originalTokens ?? 0) - (f.foldedTokens ?? 0));
      const rangeCn = formatTurnRangeChinese(f.turns, f.startTurn, f.endTurn);
      lines.push(
        `| ${idx + 1} | ${escapePipe(f.title)} | ${rangeCn} | ${f.originalTokens ?? 0} | ${f.foldedTokens ?? 0} | -${saved} | \`${f.fileName}\` |`
      );
    });
  }

  lines.push("");
  await atomicWriteText(join(dir, "INDEX.md"), lines.join("\n"));
}

function escapePipe(str) {
  return String(str ?? "").replace(/\|/g, "\\|").replace(/\n/g, " ");
}

function sanitizeSegment(str) {
  return String(str ?? "session").replace(/[^a-zA-Z0-9._-]/g, "_").slice(0, 96);
}

export function slugifyTitle(title) {
  return String(title ?? "")
    .trim()
    .replace(/[\\/:*?"<>|\s]+/g, "-")
    .replace(/-+/g, "-")
    .replace(/^-|-$/g, "")
    .slice(0, 40);
}
